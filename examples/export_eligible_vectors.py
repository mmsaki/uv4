"""Stateful Python-vs-real-Solidity differential vectors (seed 20261023).

The oracle filters Fraction prices and sorts; it does not emulate the Solidity radix tree.
Checks matched IDs/amounts, every order's residual state, maker receipts and escrow/fee claims.
"""
import json
import random
import subprocess
import sys
from pathlib import Path
from uv4.priority_protocol.model import Protocol
from uv4.priority_protocol.scenarios import fund
from uv4.priority_protocol.arithmetic import Q96, U256, Revert
from uv4.priority_protocol.ledger import HOOK, VAULT

class Deferred(Protocol):
    def _match_incoming(self, pid, oid):
        return 0

HEADER = '''// SPDX-License-Identifier: UNLICENSED
pragma solidity ^0.8.26;
// Generated by uv4/examples/export_eligible_vectors.py. Do not edit expectations manually.
import {FormalMatchD} from "../formal/FormalMatchD.sol";
import {AsyncFiller} from "@async-swap/libraries/AsyncFiller.sol";
import {AsyncOrder} from "@async-swap/types/AsyncOrder.sol";
abstract contract EligiblePythonBase is FormalMatchD {
    bytes32[] internal ids;
    AsyncOrder[] internal templates;
    Op[] internal trades;
    function _add(bool buy, uint256 a, uint256 q, uint256 fee) internal {
        address maker = address(uint160(0x1000 + ids.length));
        ids.push(_rest(key, maker, !buy, a, q, fee));
        templates.push(AsyncOrder(key, maker, !buy, a, q, fee, 2**96, _saltOf(maker,a,q,fee)));
    }
    function _cancel(uint256 i) internal {
        _run(_one(_cAs(templates[i].owner,address(hook),abi.encodeCall(hook.cancelOrder,(templates[i])))));
    }
    function _reprice(uint256 i, uint256 q) internal {
        vm.prank(templates[i].owner);
        hook.updatePrice(templates[i], q);
    }
    function _repriceReject(uint256 i, uint256 q) internal {
        vm.prank(templates[i].owner);
        vm.expectRevert(AsyncFiller.PriorityFeeTooSmall.selector);
        hook.updatePrice(templates[i], q);
    }
    function _match(uint8 cap, uint256 expected) internal {
        vm.recordLogs();
        bytes[] memory result = _runR(_one(_c(address(hook),abi.encodeCall(hook.matchBook,(key,cap)))));
        assertEq(abi.decode(result[0],(uint8)),expected,"Python match count");
        Op[] memory ops = _ops(vm.getRecordedLogs());
        delete trades;
        for(uint256 i; i<ops.length; ++i) if(ops[i].kind==OP_MATCHED) trades.push(ops[i]);
        assertEq(trades.length,expected,"Python event count");
    }
    function _trade(uint256 n,uint256 s,uint256 b,uint256 a,uint256 q) internal view {
        assertEq(trades[n].tag,ids[s],"Python selected sell");
        assertEq(trades[n].tag2,ids[b],"Python selected buy");
        assertEq(trades[n].amount,a,"Python asset transfer");
        assertEq(trades[n].amount2,q,"Python USDC transfer");
    }
    function _state(uint256 i,uint256 a,uint256 q,uint256 f,uint256 seq,uint256 price) internal view {
        AsyncFiller.OrderInfo memory o = _info(poolId,ids[i]);
        assertEq(o.amountIn,a,"Python remaining input");
        assertEq(o.amountOutMin,q,"Python remaining minimum");
        assertEq(o.priorityFee,f,"Python remaining fee");
        assertEq(o.sequence,seq,"Python sequence");
        assertEq(o.price,price,"Python bucket");
    }
    function _wallet(uint256 i,uint256 a,uint256 q) internal view {
        assertEq(token0.balanceOf(templates[i].owner),a,"Python asset receipts/refunds");
        assertEq(token1.balanceOf(templates[i].owner),q,"Python quote receipts/refunds");
    }
    function _owed(uint256 i,uint256 a,uint256 q) internal view {
        assertEq(manager.balanceOf(templates[i].owner,uint160(address(token0))),a,"Python asset claims");
        assertEq(manager.balanceOf(templates[i].owner,uint160(address(token1))),q,"Python quote claims");
    }
    function _claims(uint256 a,uint256 q,uint256 fa,uint256 f) internal view {
        assertEq(manager.balanceOf(address(hook),uint160(address(token0))),a,"Python asset escrow");
        assertEq(manager.balanceOf(address(hook),uint160(address(token1))),q,"Python quote+bid escrow");
        assertEq(manager.balanceOf(address(hook.feeVault()),uint160(address(token0))),fa,"Python asset trade fees");
        assertEq(manager.balanceOf(address(hook.feeVault()),uint160(address(token1))),f,"Python settled bids and quote trade fees");
    }
}
'''

stats = {'seed':20261023,'campaigns':0,'operations':0,'matches':0,'state_checks':0,'wallet_checks':0}
parts=[HEADER]
for campaign in range(8):
    r=random.Random(20261023+campaign)
    m=Deferred(numeraire='0x0000000000000000000000000000000000000002')
    pid=m.initialize('0x0000000000000000000000000000000000000001',m.numeraire,Q96)
    pool=m.pools[pid]
    oids=[]; deposits=[]; lines=[]
    def state():
        pool=m.pools[pid]
        for i,oid in enumerate(oids):
            o=pool.orders.get(oid)
            vals=(o.amount_in,o.minimum_out,o.priority_fee,o.sequence,o.price) if o else (0,0,0,0,0)
            lines.append(f'        _state({i},'+','.join(map(str,vals))+');')
            stats['state_checks']+=1
            who=f'owner-{i}'
            a=m.ledger.balances[who,pool.asset]-10**60+deposits[i][0]
            q=m.ledger.balances[who,pool.numeraire]-10**60+deposits[i][1]
            lines.append(f'        _wallet({i},{a},{q});'); stats['wallet_checks']+=1
            lines.append(f'        _owed({i},{m.ledger.claims[who,pool.asset]},{m.ledger.claims[who,pool.numeraire]});')
        lines.append(f'        _claims({m.ledger.claims[HOOK,pool.asset]},{m.ledger.claims[HOOK,pool.numeraire]},{m.ledger.claims[VAULT,pool.asset]},{m.ledger.claims[VAULT,pool.numeraire]});')
    def add(buy,a,q,fee):
        global pool
        who=f'owner-{len(oids)}';fund(m,pid,who)
        oid=m.create(pid,who,buy,a,q,fee);oids.append(oid);pool=m.pools[pid]
        deposits.append((0,a+fee) if buy else (a,fee))
        lines.append(f'        _add({str(buy).lower()},{a},{q},{fee});');stats['operations']+=1
    def match(cap):
        start=len(m.events);n=m.match_book(pid,cap)
        lines.append(f'        _match({cap},{n});');stats['operations']+=1;stats['matches']+=n
        ts=[e for e in m.events[start:] if e[0]=='Matched']
        for j,e in enumerate(ts): lines.append(f'        _trade({j},{oids.index(e[2])},{oids.index(e[3])},{e[4]},{e[5]});')
    if campaign < 3:
        # Normal bucket, lower clamp, upper clamp. Both sides have noncrossing fee leaders.
        a,q,bada,badq= [(10**18,10**9,2*10**15-1,2_000_000),
                       (10**36,10**12,2*10**30,3_800_000*10**6),
                       (1,10**30,1,10**36)][campaign]
        add(False,bada,badq,100005)
        # A weaker buy at the same boundary (normal case uses q+1 to retain the key).
        if campaign==0: add(True,q+1,a+10**9+1,100004)
        elif campaign==1: add(True,q,a*2,100004)
        else: add(True,q//2,a,100004)
        for i in range(20): add(False,a,q,100000+i%3)
        for i in range(20): add(True,q,a,100000+i%3)
        state()
        for cap in (1,2,4,8,8,8): match(cap);state()
    else:
        for step in range(70):
            live=[(i,pool.orders[oid]) for i,oid in enumerate(oids) if oid in pool.orders]
            action=r.randrange(10)
            if action<5 or not live:
                buy=bool(r.randrange(2)); size=r.randrange(1,8)
                if campaign==7: # tiny integer lots and zero bids stress unchanged-rank refresh
                    a=r.randrange(1,30);q=r.randrange(1,30);fee=0
                else:
                    a=size*(10**9 if buy else 10**18)
                    q=size*(10**18 if buy else 10**9)+r.choice([-1,0,1,2])
                    fee=100000+r.randrange(4)
                add(buy,a,q,fee)
            elif action<8: match(r.choice([1,2,4,8]))
            elif action==8:
                i,o=r.choice(live);new=max(1,o.minimum_out+r.choice([-2,-1,1,2]))
                try:
                    m.update_price(pid,o.id,o.owner,new)
                    lines.append(f'        _reprice({i},{new});')
                except Revert as error:
                    assert 'PriorityFeeTooSmall' in str(error), error
                    lines.append(f'        _repriceReject({i},{new});')
                stats['operations']+=1
            else:
                i,o=r.choice(live);m.cancel(pid,o.id,o.owner);lines.append(f'        _cancel({i});');stats['operations']+=1
            state()
        for _ in range(4):match(8);state()
    # Split long trace into functions, preserving storage across phases.
    chunks=[lines[i:i+150] for i in range(0,len(lines),150)]
    parts.append(f'contract EligiblePython{campaign}Test is EligiblePythonBase {{\n    function test_pythonStatefulTrace() public {{\n'+''.join(f'        _phase{i}();\n' for i in range(len(chunks)))+'    }\n')
    for i,chunk in enumerate(chunks):parts.append(f'    function _phase{i}() internal {{\n'+'\n'.join(chunk)+'\n    }\n')
    parts.append('}\n');stats['campaigns']+=1
target = Path(sys.argv[1])
huff = '--huff' in sys.argv[2:]
source = '\n'.join(parts)
if huff:
    source = source.replace('import {FormalMatchD} from "../formal/FormalMatchD.sol";', 'import {CurrentHuffHarness, CurrentOrderInfo} from "./CurrentHuffHarness.sol";')
    source = source.replace('is FormalMatchD', 'is CurrentHuffHarness')
    source = source.replace('import {AsyncFiller} from "@async-swap/libraries/AsyncFiller.sol";', 'import {IAsyncFiller as AsyncFiller} from "src/interface/IAsyncFiller.sol";')
    source = source.replace('"@async-swap/types/AsyncOrder.sol"', '"src/interface/types/AsyncOrder.sol"')
    source = source.replace('AsyncFiller.OrderInfo memory', 'CurrentOrderInfo memory')
    out = target / 'test/current/EligiblePythonVectors.t.sol'
else:
    out = target / 'test/security/EligiblePythonVectors.t.sol'
out.write_text(source)
subprocess.run(['forge','fmt',str(out)],cwd=Path(sys.argv[1]),check=True)
report=Path('docs/priority_protocol/eligible_vectors.json');report.write_text(json.dumps(stats,indent=2)+'\n')
print(json.dumps(stats,indent=2))
